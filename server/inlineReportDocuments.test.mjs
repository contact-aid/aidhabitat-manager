import assert from 'node:assert/strict';
import test from 'node:test';
import { mergeInlineDocuments, reportDocumentAliases } from './reports/inlineReportDocuments.mjs';
import { photosForVisitTag } from './reports/generateVisitReport.mjs';
const patient = 'nocodb-beneficiaire-69';
const tag = 'Visite - Accessibilité';
const docs = ['a', 'b', 'c'].map(id => ({ id, clientDocumentId: `doc_${id}`, tags: [tag] }));
const encode = value => Buffer.from(value).toString('base64').replaceAll('+','-').replaceAll('/','_');
test('report resolves the padded patient-scoped identity generated by Flutter', () => {
  const orders = new Map(docs.map((d,i) => [`remote_doc_${encode(patient)}_${encode(d.id)}`, [2,0,1][i]]));
  const merged = mergeInlineDocuments(docs, new Map(), orders, patient);
  assert.deepEqual(photosForVisitTag(merged,tag).map(d=>d.id), ['b','c','a']);
  assert.deepEqual(merged.map(d=>d.categoryOrder), [2,0,1]);
  assert(!reportDocumentAliases(docs[0], 'other-patient').some(id => orders.has(id)));
});
test('uploaded, legacy and client identities still override remote ranks, including rank zero', () => {
  for (const identity of ['b','remote_doc_b','doc_b']) {
    const merged = mergeInlineDocuments(docs.map(d=>({...d,categoryOrder:8})), new Map(), new Map([[identity,0]]),patient);
    assert.equal(photosForVisitTag(merged,tag)[0].id,'b');
  }
});
